"""Character/identity, scene and prop sheets are enforced at submission."""
VERSION = 'asset-sheet-v5'
ASSET_KINDS = ('character', 'location', 'prop')
COMMON = (
    '资产设定图统一规则：所有视觉风格（包括自定义风格）均遵循下列视图布局，'
    '画风、笔触、材质表现仍按当前作品设定，不强制转成写实。'
    '一张图只展示同一个资产，各视图的身份、比例、形状、颜色和细节必须一致；'
    '画面清晰，各视图分区排列、留出间隔，不重叠，不裁切主体。'
    '不添加标题、视角标签、编号、字幕、水印或无关文字。'
)
LAYOUTS = {
    'character': (
        '角色设定图：纯白背景，横向结构化排版，左侧三个完整全身视图，分别为正面、侧面、背面；'
        '右侧二乘三六格面部特写，分别为正面、左侧、右侧、左前四十五度、右前四十五度及面部细节。'
        '全身视图完整展示头顶到脚底，直立自然站姿，双臂自然下垂，比例与尺寸统一。'
        '全部视图必须是同一个角色、同一年龄、同一发型、同一服装和同一当前状态，'
        '脸型、五官、肤色与衣饰细节一致；均匀照明，清楚呈现外观，不带剧情场景和动作过程。'
        '非人类角色按其自身形态展示完整身体及头部细节，不强行改变为人形。'
    ),
    'location': (
        '场景设定图：使用二乘二四宫格，展示同一空间的正向、反向、左向、右向四个视角。'
        '门窗、墙体、家具、道路及固定设施的位置和相对关系保持一致，'
        '反向视角必须对应同一空间的另一面，不是把正向图镜像或随意改造布局。'
        '保留完整场景背景，统一时间、天气、光源、色调和材质；无人物、无剧情动作。'
    ),
    'prop': (
        '道具设定图：使用二乘三六宫格，分别展示同一道具的正面、背面、左侧、右侧、'
        '顶部和底部（可用轻微倾斜视角看清厚度及结构）。'
        '每格只展示该道具，轮廓、尺寸比例、材质、颜色、磨损和装饰完全一致；'
        '不凭空增加背面图案、文字或部件。纯白背景，均匀照明，无手持人物和剧情环境。'
    ),
}
SHOT = (
    '分镜图片规则：只生成一张完整的镜头画面，禁止多宫格、拼版、人物三视图或道具设定图。'
    '若参考图是多视角资产设定图，只借用对应视角的身份、服装、空间结构及道具细节，'
    '不要复制参考图的白底、分隔线、重复人物或拼版布局；按本镜头场景与构图呈现。'
)


def rules(target):
    kind = target.get('kind')
    return COMMON + LAYOUTS[kind] if kind in LAYOUTS else SHOT


def enforce(prompt, target):
    rule = rules(target)
    if not rule: return prompt
    return prompt if rule in prompt else prompt.rstrip() + '\n\n' + rule


def prompt_generation_rules():
    return ('以下底层规则优先于技能中关于单图或拼版的建议，仅作用于 image_prompt，'
            '不作用于 video_prompt。角色卡与身份卡均使用白底全身三视图和六格面部特写；'
            '身份卡保持来源角色的脸型、五官与体态，只改变指定服装或状态，默认身份复用角色图。'
            '以下布局规则用于角色、身份、场景和道具：\n' + COMMON + '\n' +
            '\n'.join(kind + '：' + layout for kind, layout in LAYOUTS.items()) + '\n' + SHOT)
